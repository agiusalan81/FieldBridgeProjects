import { createFileRoute, Link } from "@tanstack/react-router";
import { Button } from "@/components/ui/button";
import { PROJECT_ID, useTable, eur, valuation } from "@/lib/db";
import { pageHead } from "@/lib/head";

export const Route = createFileRoute("/_authenticated/certificate/$id")({
  head: () => pageHead("Interim Payment Certificate", "Printable interim payment certificate for an application for payment."),
  component: Certificate,
});

function Certificate() {
  const { id } = Route.useParams();
  const a = useTable("payment_applications").data?.find((x) => x.id === id);
  const p = useTable("projects").data?.find((x) => x.id === PROJECT_ID);
  if (!a) return <p className="p-6 text-sm text-muted-foreground">Loading certificate…</p>;
  const v = valuation(a);
  const no = `AFP-${String(a.application_number).padStart(2, "0")}`;
  const rows: [string, number][] = [["Value of work executed (cumulative)", a.gross_work_value], ["Add: approved variations", a.approved_variations], ["Gross valuation", v.gross], [`Less: retention (${a.retention_percent}%)`, -v.retention], ["Net cumulative", v.netCumulative], ["Less: previously certified", -a.previous_certified]];
  return (
    <div className="mx-auto max-w-3xl">
      <div className="mb-3 flex justify-between print:hidden"><Link to="/commercials" className="text-sm underline">← Back to valuations</Link><Button onClick={() => window.print()}>Print / Save as PDF</Button></div>
      <article className="space-y-5 rounded-md border bg-card p-8">
        <header className="flex justify-between border-b pb-4">
          <div><h1 className="font-display text-2xl font-bold uppercase">Interim Payment Certificate</h1><p className="text-sm text-muted-foreground">Certificate {no} · Period ending {a.period_end}</p></div>
          <div className="text-right text-sm"><b>{p?.name}</b><div>{p?.project_number}</div><div className="text-muted-foreground">{p?.site_address}</div></div>
        </header>
        <p className="text-sm">Employer: <b>{p?.employer_name ?? "—"}</b></p>
        <table className="w-full text-sm"><tbody>
          {rows.map(([l, n]) => <tr key={l} className="border-b"><td className="py-2">{l}</td><td className="py-2 text-right font-mono">{eur(n)}</td></tr>)}
          <tr><td className="py-3 text-base font-bold">Amount due this certificate</td><td className="py-3 text-right font-mono text-lg font-bold">{eur(v.dueThisPeriod)}</td></tr>
        </tbody></table>
        <p className="text-sm">Status: <b>{a.status}</b></p>
        <div className="grid grid-cols-2 gap-8 pt-10 text-sm"><div className="border-t pt-2">Certified by (QS / PM)</div><div className="border-t pt-2">Date</div></div>
        <p className="text-xs text-muted-foreground">Amounts exclude VAT. Generated by FieldBridge Projects — usable without FieldBridge Books.</p>
      </article>
    </div>
  );
}
